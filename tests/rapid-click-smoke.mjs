import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import assert from 'node:assert/strict';
import {spawn} from 'node:child_process';
import {once} from 'node:events';
import {ROOT,DATA_HOME} from '../runtime/paths.mjs';
assert.equal(process.platform,'win32','native rapid click validation requires Windows');
const output=path.resolve(process.argv[2]||path.join(ROOT,'qa-rapid-click'));
const dataDir=fs.mkdtempSync(path.join(os.tmpdir(),'whale-rapid-click-'));
fs.mkdirSync(output,{recursive:true});
fs.writeFileSync(path.join(dataDir,'ui-state.json'),JSON.stringify({'dshw-role':'default','dshw-pos':JSON.stringify({v:2,hAnchor:'left',hDist:180,vAnchor:'top',vDist:180})}));
const env={...process.env,WHALE_DESKTOP_TEST:'1',WHALE_RAPID_CLICK:'1',WHALE_DESKTOP_VERIFY_DIR:output};delete env.ELECTRON_RUN_AS_NODE;
const executable=process.env.WHALE_TEST_ELECTRON||path.join(DATA_HOME,'desktop-runtime/node_modules/electron/dist/electron.exe');
const child=spawn(executable,[path.join(ROOT,'desktop/main.cjs'),'--whale-data='+dataDir],{env,windowsHide:true,stdio:['ignore','pipe','pipe']});
let diagnostics='';child.stdout.resume();child.stderr.on('data',bytes=>{diagnostics=(diagnostics+bytes).slice(-5000);});
const timeout=setTimeout(()=>child.kill(),90000);const [code]=await once(child,'close');clearTimeout(timeout);
const reportFile=path.join(output,'rapid-click.json');
const report=fs.existsSync(reportFile)?JSON.parse(fs.readFileSync(reportFile,'utf8')):{ok:false,diagnostics,dataDir};
assert.equal(code,0,JSON.stringify(report));assert.equal(report.ok,true,JSON.stringify(report));
process.stdout.write(JSON.stringify({ok:report.ok,scenarios:report.scenarios.length,alphaLostEvents:report.alphaLostEvents,reportFile,dataDir})+'\n');
