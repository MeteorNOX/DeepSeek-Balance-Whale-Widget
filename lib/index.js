    // 子代理聚合：把 origin=subagent 的子孙会话费用并入根会话。
    // records 含 header.parentSession，构建 parent→children 表，DFS 求和。
    // 返回 rootId -> { amount(组), own(自身), sub(子孙), subCount, hit, miss, out, models }
    function aggregateSessionCosts(records, ownCosts) {
      const children = new Map()
      const rootIds = []
      for (const rec of records) {
        const id = rec && rec.header ? rec.header.id : null
        if (!id) continue
        const parent = rec.header.parentSession
        if (parent && parent !== id) {
          let list = children.get(parent)
          if (!list) {
            list = []
            children.set(parent, list)
          }
          list.push(id)
        } else {
          rootIds.push(id)
        }
      }
      const merged = {}
      const visit = (id) => {
        const own = ownCosts[id]
        if (!own) return null
        let sub = 0
        let subCount = 0
        let hit = own.hit
        let miss = own.miss
        let out = own.out
        const models = { ...own.models }
        const kids = children.get(id) || []
        for (const cid of kids) {
          const c = visit(cid)
          if (!c) continue
          sub += c.amount // 该子节点整组总价（含孙辈）
          subCount += c.subCount + 1
          hit += c.hit
          miss += c.miss
          out += c.out
          for (const m in c.models) models[m] = (models[m] || 0) + c.models[m]
        }
        return { amount: own.amount + sub, sub, subCount, hit, miss, out, models }
      }
      for (const id of rootIds) {
        const g = visit(id)
        if (g) merged[id] = g
      }
      return merged
    }

