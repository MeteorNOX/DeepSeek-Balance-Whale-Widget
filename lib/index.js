    // 计价口径与「每轮消耗」完全一致：按每事件真实模型（flash/pro 档）+ 事件时刻
    // 峰谷定价。live 会话直接扫描内存事件表（零落盘）；冷会话经 sessionQuery.load
    // 全量扫描一次后缓存（持久化日志只读，进程期内无需重扫）。
