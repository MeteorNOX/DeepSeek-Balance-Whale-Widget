//! 宿主外壳层（Shell）
//!
//! 承载**原生宿主资源**：Tauri 窗口（挂件窗口、配置窗口）与系统托盘的
//! 创建、复用与几何读取。
//!
//! 与 `frontend/` 的区别：前端负责**界面渲染**（HTML/CSS/JS），
//! 本层负责**窗口与托盘这类操作系统级资源**，前端无法自行创建。
//!
//! - [`window`]：挂件 / 配置窗口的创建与复用、窗口几何与显示器工作区读取；
//! - [`tray`]：系统托盘图标与菜单。
//!
//! 依赖方向：本层不依赖 `api` 与 `application`；只有 `api` 与入口
//! `lib.rs` 会调用本层，是分层图的最上层（与 `api` 同层）。

pub mod tray;
pub mod window;
